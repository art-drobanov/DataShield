namespace DataShield.Codec.StreamScanner;

// ─────────────────────────────────────────────────────────────────────────────
//  Обработчик окна сканера
// ─────────────────────────────────────────────────────────────────────────────

/// <summary>
/// Делегат обработки окна побайтового сканера.
///
/// Возвращает продвижение потока в байтах: при успехе — смещение, на которое
/// проматывается поток (обычно размер окна), при неуспехе декода сканер
/// сдвигает окно на 1 байт. Найденный пакет возвращается через
/// <paramref name="emitted"/> (копия; null — окно не распознано).
///
/// Окно действительно только внутри вызова: делегат не должен сохранять
/// ссылку на него.
/// </summary>
/// <param name="window">Текущее окно потока (WindowSize байт).</param>
/// <param name="emitted">Распознанный пакет либо null.</param>
/// <returns>Число байт продвижения потока (≥ 1).</returns>
public delegate int WindowHandler(ReadOnlySpan<byte> window, out byte[]? emitted);
