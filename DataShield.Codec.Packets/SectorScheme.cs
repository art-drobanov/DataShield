namespace DataShield.Codec.Packets;

/// <summary>
/// Схема хеширования секторов данных.
///
/// <b>Classic</b> — D1 ‖ D2 ‖ Trunc9(SHA-256(H5 ‖ D1 ‖ D2)): явный номер
/// сектора в пакете, стойкость 72 бита на пакет, приём — ровно один хеш.
///
/// <b>VirtualIndex</b> — payload ‖ Trunc11(SHA-256(H5 ‖ payload ‖ idx LE)):
/// номер сектора в пакет не записывается, а неявно кодируется индексом в
/// хеше; на приёме индекс восстанавливается перебором K вариантов (K —
/// число секторов файла). Стойкость на файл — 88 − log₂K бит, выгода
/// против Classic при K &lt; 65536; цена — до K хешей на пакет при проверке
/// (курсор прихода сокращает до O(1) для последовательных потоков).
/// </summary>
public enum SectorScheme
{
    /// <summary>Классическая схема: номер сектора в пакете, Trunc9.</summary>
    Classic = 0,

    /// <summary>Виртуальный индекс: payload + Trunc11, индекс восстанавливается перебором.</summary>
    VirtualIndex = 1
}
