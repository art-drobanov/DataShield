namespace DataShield.Codec.Packets;

// ─────────────────────────────────────────────────────────────────────────────
//  Режим работы декодера с сигнатурными пакетами SHA-512
// ─────────────────────────────────────────────────────────────────────────────

/// <summary>
/// Режим работы декодера с сигнатурными пакетами SHA-512.
///
/// Расширенная проверка — Exact(SHA-256) &amp; Any(SHA-512): после базовой
/// проверки SHA-256 собранный файл должен быть подтверждён хотя бы одной
/// сигнатурой из принятых сигнатурных пакетов.
/// </summary>
public enum SignatureMode
{
    /// <summary>
    /// Базовый режим: сигнатурные пакеты детектируются, но игнорируются
    /// при сборке файла (расширенная проверка не выполняется).
    /// </summary>
    Base = 0,

    /// <summary>
    /// Автоматический режим (по умолчанию): расширенная проверка SHA-512
    /// активируется, если из потока принят хотя бы один сигнатурный пакет.
    /// </summary>
    Auto = 1,

    /// <summary>Принудительный режим: расширенная проверка активна всегда.</summary>
    Force = 2
}
