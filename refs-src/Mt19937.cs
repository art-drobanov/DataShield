/// <summary>
/// Генератор псевдослучайных чисел «Вихрь Мерсенна» MT19937
/// (классический вариант 1997 года с инициализацией sgenrand),
///
/// Состояние генератора — 624 32-битных слова, из которых на каждом
/// «прогоне» порождаются новые значения линейной рекуррентой над GF(2)
/// (операции xor/сдвиги), а каждое выдаваемое число дополнительно
/// закаляется (tempering) обратимыми преобразованиями.
/// Период составляет 2^19937 - 1.
/// </summary>
public sealed class Mt19937 // 53d7458a5859d95571f852194563fb6ce627d3541784897364cf2fec7b708a4a
{
    private const int MtN = 624;   // размер состояния (в словах)
    private const int MtM = 397;   // шаг второй половины рекурренты
    private const uint MatrixA = 0x9908b0df;    // матрица A рекурренты над GF(2)
    private const uint UpperMask = 0x80000000;  // старший бит слова
    private const uint LowerMask = 0x7fffffff;  // все биты, кроме старшего

    /// <summary>Mag01[0]=0, Mag01[1]=MatrixA — выбор коэффициента по младшему биту y.</summary>
    private static readonly uint[] Mag01 = { 0x0, MatrixA };

    private readonly uint[] _mt = new uint[MtN];
    private int _mti = MtN + 1;  // индекс следующего слова; >= MtN означает «нужно перегенерировать»

    /// <summary>Создаёт генератор с сидом по умолчанию 4357 (как в оригинальной реализации).</summary>
    public Mt19937() : this(4357) { }

    /// <summary>Создаёт генератор с заданным сидом.</summary>
    public Mt19937(uint seed) => Sgenrand(seed);

    /// <summary>
    /// Инициализация состояния (вариант sgenrand 1997 года): первое слово —
    /// сид, каждое следующее получается умножением предыдущего на 69069
    /// (один из множителей Кнута, дающий хорошую перемешанность битов).
    /// </summary>
    private void Sgenrand(uint seed)
    {
        _mt[0] = seed;
        for (_mti = 1; _mti < MtN; _mti++)
            _mt[_mti] = 69069u * _mt[_mti - 1];
    }

    /// <summary>
    /// Возвращает очередное псевдослучайное 32-битное беззнаковое число.
    /// Когда состояние исчерпано (_mti достигло MtN), прогоняет полный
    /// цикл рекурренты: для каждого слова склеиваются старший бит
    /// текущего и младшие 31 бит следующего (y), затем новое значение —
    /// xor слова на MtM позиций дальше, y>>1 и, при единичном младшем
    /// бите y, матрицы A. Закалка выхода четырьмя xor-сдвигами
    /// уничтожает линейные корреляции низших бит.
    /// </summary>
    public uint Genrand()
    {
        if (_mti >= MtN)
        {
            uint y;
            int kk;
            for (kk = 0; kk < MtN - MtM; kk++)
            {
                y = (_mt[kk] & UpperMask) | (_mt[kk + 1] & LowerMask);
                _mt[kk] = _mt[kk + MtM] ^ (y >> 1) ^ Mag01[y & 0x1];
            }
            for (; kk < MtN - 1; kk++)
            {
                y = (_mt[kk] & UpperMask) | (_mt[kk + 1] & LowerMask);
                _mt[kk] = _mt[kk + (MtM - MtN)] ^ (y >> 1) ^ Mag01[y & 0x1];
            }
            y = (_mt[MtN - 1] & UpperMask) | (_mt[0] & LowerMask);
            _mt[MtN - 1] = _mt[MtM - 1] ^ (y >> 1) ^ Mag01[y & 0x1];

            _mti = 0;
        }

        // Закалка (tempering) — обратимая развязка битов.
        uint r = _mt[_mti++];
        r ^= r >> 11;
        r ^= (r << 7) & 0x9d2c5680;
        r ^= (r << 15) & 0xefc60000;
        r ^= r >> 18;
        return r;
    }

    /// <summary>Равномерное число типа double в диапазоне [0, 1].</summary>
    public double NextDouble01() => Genrand() * (1.0 / 4294967295.0);

    /// <summary>
    /// Выборка без возвращения по алгоритму S Кнута (TAOCP т. 2, 3.4.2):
    /// заполняет pos ровно k различными позициями из диапазона [0, n),
    /// выбираемыми равномерно, в возрастающем порядке. Используется
    /// бенчмарком для моделирования стёртых пакетов.
    /// </summary>
    public void GeneratePositions(int n, int k, int[] pos)
    {
        int size = n;
        int w = k;
        do
        {
            // Каждый следующий кандидат берётся с вероятностью w/size —
            // классическая схема последовательного выбора.
            if (NextDouble01() * size <= w)
            {
                pos[k - w] = n - size;
                w--;
            }
            size--;
        }
        while (size != 0);
    }
}