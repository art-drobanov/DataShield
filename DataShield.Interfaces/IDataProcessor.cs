namespace DataShield.Interfaces;

// ─────────────────────────────────────────────────────────────────────────────
//  Обработчик данных (чёрный ящик с входом)
// ─────────────────────────────────────────────────────────────────────────────

/// <summary>
/// Обработчик данных: источник данных, дополнительно принимающий данные на
/// вход и обрабатывающий их внутри своего «чёрного ящика». Результат
/// обработки публикуется собственным (отдельным) событием
/// <see cref="IDataSource.DataReady"/>, что позволяет выстраивать цепочки
/// обработчиков.
/// </summary>
public interface IDataProcessor : IDataSource
{
    /// <summary>Подключить источник данных на вход обработчика.</summary>
    void Attach(IDataSource source);

    /// <summary>Отключить входной источник.</summary>
    void Detach();

    /// <summary>
    /// Сигнал конца входных данных: остаток выходного буфера выбрасывается
    /// событием DataReady, обработчик останавливается.
    /// </summary>
    void Complete();
}
