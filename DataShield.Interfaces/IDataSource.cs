namespace DataShield.Interfaces;

// ─────────────────────────────────────────────────────────────────────────────
//  Источник данных с буферизацией
// ─────────────────────────────────────────────────────────────────────────────

/// <summary>
/// Источник данных с буферизацией и событийной моделью выдачи.
///
/// Жизненный цикл: источник может быть запущен или остановлен. После запуска
/// источник читает данные в буфер размером <see cref="BufferSize"/>
/// (объёмы невелики, поэтому побайтовое чтение допустимо). Заполненный буфер
/// объявляется событием <see cref="DataReady"/>; перед выбросом события чтение
/// приостанавливается и возобновляется после вычитки буфера клиентом через
/// делегат. При исчерпании данных (EOF/конец потока) выбрасывается готовность
/// с остатком буфера, после чего источник останавливается сам.
///
/// Остановленный источник не читает данные в буфер, но отдаёт имеющийся
/// в буфере остаток.
/// </summary>
public interface IDataSource
{
    /// <summary>Размер буфера источника, байт.</summary>
    int BufferSize { get; }

    /// <summary>Источник запущен и читает данные в буфер.</summary>
    bool IsRunning { get; }

    /// <summary>Задача завершения источника (EOF или остановка).</summary>
    Task Completion { get; }

    /// <summary>
    /// Ошибка, прервавшая чтение источника (например, сбой ввода-вывода),
    /// либо null, если чтение завершилось без сбоёв. При наличии ошибки
    /// задача <see cref="Completion"/> завершается этой же ошибкой.
    /// </summary>
    Exception? Error { get; }

    /// <summary>Готовность данных: передаётся делегат вычитки буфера.</summary>
    event DataReadyHandler? DataReady;

    /// <summary>Запустить чтение данных в буфер.</summary>
    void Start();

    /// <summary>Остановить чтение; остаток буфера отдаётся событием DataReady.</summary>
    void Stop();
}
