using DataShield.Codec.StreamProcessor;

namespace DataShield.Codec;

// ─────────────────────────────────────────────────────────────────────────────
//  Результат декодирования одного слота приёма
// ─────────────────────────────────────────────────────────────────────────────

/// <summary>
/// Результат декодирования одного файла (слота приёма) из FEC-потока:
/// сам слот с деталями приёма (карты валидности и коллизий, покрытия,
/// заголовок) и собранное содержимое — либо null, если восстановить файл
/// не удалось (повреждения превысили избыточность).
/// </summary>
/// <param name="Slot">Слот приёма с деталями (не null).</param>
/// <param name="Content">Собранное содержимое файла или null при неудаче.</param>
public sealed record DecodeResult(ReceptionSlot Slot, byte[]? Content);
